#!/usr/bin/env python3
"""Write dewglyphs.h: the PS5 glyphs the bridge draws into the game's fonts.

    python3 make_bridge_glyphs.py > dewglyphs.h

build.sh runs this. Each glyph is drawn once, large, by the same code
patch_for_ps5.py uses for font_package.bin, cut down to its own outline, and
stored in the font package's packed pixel format. The bridge scales it to
whatever size a font needs (see dewfont.c).
"""
import patch_for_ps5 as P

HEIGHT = 96                 # pixels for the 100 units a glyph is designed on
# width, in the same units, of the box each kind of glyph is drawn in
WIDE = {'L1': 116, 'R1': 116, 'L2': 92, 'R2': 92}
FACES = ('Cross', 'Circle', 'Square', 'Triangle')   # drawn filled and as a ring


def master(make, units, filled):
    width = HEIGHT * units // 100
    pixels = P._raster(make(float(units), filled), width, HEIGHT, float(units), 100.0)
    rows = [pixels[y * width:(y + 1) * width] for y in range(HEIGHT)]
    ys = [y for y in range(HEIGHT) if any(p[3] for p in rows[y])]
    xs = [x for x in range(width) if any(row[x][3] for row in rows)]
    cut = [p for row in rows[ys[0]:ys[-1] + 1] for p in row[xs[0]:xs[-1] + 1]]
    w, h = xs[-1] - xs[0] + 1, ys[-1] - ys[0] + 1
    assert w <= 128 and h <= 128
    return w, h, P.pack_pixels(cut)


def main():
    makers = {}
    for name, make in P.FONT_GLYPHS.values():
        makers.setdefault(name, make)
    names = sorted(makers)
    print('/* Generated by make_bridge_glyphs.py; do not edit. */')
    table = []
    for name in names:
        ids = []
        for filled in ((True, False) if name in FACES else (True,)):
            w, h, data = master(makers[name], WIDE.get(name, 100), filled)
            ident = 'm_%s%s' % (name.lower(), '' if filled else '_ring')
            print('static const unsigned char %s[] = {' % ident)
            for i in range(0, len(data), 20):
                print('\t' + ''.join('%d,' % b for b in data[i:i + 20]))
            print('};')
            ids.append('{ %d, %d, sizeof(%s), %s }' % (w, h, ident, ident))
        if len(ids) == 1:
            ids.append('{ 0, 0, 0, 0 }')
        table.append('\t{ %s },\t/* %d: %s */' % (', '.join(ids), len(table), name))
    print('/* a glyph to try first and, for the face buttons, a lighter one to fall back on */')
    print('static const struct font_master { unsigned short w, h, size; const unsigned char *data; }')
    print('font_masters[][2] = {')
    print('\n'.join(table))
    print('};')
    print('static const struct { unsigned short character; unsigned char master; } font_characters[] = {')
    for character in sorted(P.FONT_GLYPHS):
        print('\t{ 0x%04X, %d },' % (character, names.index(P.FONT_GLYPHS[character][0])))
    print('};')


if __name__ == '__main__':
    main()
